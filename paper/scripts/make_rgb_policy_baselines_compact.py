#!/usr/bin/env python3
"""Generate the compact rgb-policy baselines figure template.

Reads the unified 100x100 dualtex evaluation conditions and emits the LaTeX
picture template at paper/figures/rgb-policy-baselines-compact.tex. Bars stack
the Seen-asset and Unseen-asset contributions to each Overall success rate.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIGURE = ROOT / "paper/figures/rgb-policy-baselines-compact.tex"

RUNS = {
    ("Fold", "pi05"): "outputs/evaluations/pi05_rgb_fold_generated_unified100x100_dualtex_v2",
    ("Fold", "groot"): "outputs/evaluations/groot_rgb_fold_generated_unified100x100_dualtex_v1",
    ("Fold", "diffusion"): "outputs/evaluations/diffusion_rgb_fold_generated_unified100x100_dualtex_v1",
    ("Flatten", "pi05"): "outputs/evaluations/pi05_rgb_flatten_generated_unified100x100_dualtex_v1_instantaneous_score",
    ("Flatten", "groot"): "outputs/evaluations/groot_rgb_flatten_generated_unified100x100_dualtex_v1_instantaneous_score",
    ("Flatten", "diffusion"): "outputs/evaluations/diffusion_rgb_flatten_generated_unified100x100_dualtex_v1_instantaneous_score",
}
MODELS = [("pi05", "$\\pi_{0.5}$"), ("groot", "GR00T"), ("diffusion", "Diffusion")]

# Geometry in inches; single-column figure matching the rgb-policy family.
AXIS_X = 0.48
TICK_LABEL_X = 0.40
YLABEL_X = 0.10
BAR_W = 0.19
BAR_X = [0.54, 0.90, 1.52, 1.88, 2.50, 2.86]
FOLD_BASE, FOLD_MAX, AXIS_H = 1.65, 70.0, 1.05
FLAT_BASE, FLAT_MAX = 0.42, 44.0
FOLD_TICKS = [0, 20, 40, 60]
FLAT_TICKS = [0, 20, 40]
PANEL_CENTER_X = 1.795
FOLD_TITLE_Y = 2.74
FLAT_TITLE_Y = 1.49
TEX_LINE1_Y = 0.35
TEX_LINE2_Y = 0.235
MODEL_LABEL_Y = 0.12
LEGEND_X = 2.02
LEGEND_LABEL_X = 2.24
LEGEND_ROWS = [("Seen asset", 2.50), ("Unseen asset", 2.34)]


def success_rates(run_dir: str) -> dict:
    meta = json.loads((ROOT / run_dir / "meta.json").read_text())
    splits = meta["benchmark"]["asset_splits"]
    counts: dict[tuple[str, str], list[int]] = {}
    for line in open(ROOT / run_dir / "results.jsonl"):
        record = json.loads(line)
        texture = "train" if record["initial_state_index"] < 4 else "test"
        key = (splits[record["asset_id"]], texture)
        cell = counts.setdefault(key, [0, 0])
        cell[0] += 1
        cell[1] += int(bool(record["success"]))
    if len(counts) != 4 or any(n != 400 for n, _ in counts.values()):
        raise SystemExit(f"unbalanced cells in {run_dir}: {counts}")
    return {key: 100.0 * s / n for key, (n, s) in counts.items()}


def fmt(value: float) -> str:
    return f"{value:.4f}"




def main() -> None:
    rates = {key: success_rates(run) for key, run in RUNS.items()}
    lines: list[str] = []
    add = lines.append
    add("\\RequirePackage[T1]{fontenc}")
    add("\\documentclass[letterpaper,10pt,conference]{../ieeeconf}")
    add("\\usepackage{graphicx}")
    add("\\pagestyle{empty}")
    add("")
    add("% Generated by paper/scripts/make_rgb_policy_baselines_compact.py; edit that script instead.")
    add("% Palette from the approved rgb-policy figure family; colors encode asset splits.")
    add("\\newcommand{\\seenColor}{0.004 0.514 0.733}")
    add("\\newcommand{\\unseenColor}{1.000 0.859 0.820}")
    add("\\newcommand{\\colorpush}[1]{\\special{color push rgb #1}}")
    add("\\newcommand{\\colorpop}{\\special{color pop}}")
    add("% One stacked bar: x, baseline y, split y, top y, seen height, unseen height, total height, top label.")
    add("\\newcommand{\\stackbar}[8]{%")
    add("  \\put(#1,#2){\\colorpush{\\seenColor}\\rule{0.19in}{#5in}\\colorpop}%")
    add("  \\put(#1,#3){\\colorpush{\\unseenColor}\\rule{0.19in}{#6in}\\colorpop}%")
    add("  \\put(#1,#3){\\line(1,0){0.19}}%")
    add("  \\put(#1,#2){\\framebox(0.19,#7){}}%")
    add("  \\put(#1,#4){\\makebox(0.19,0)[b]{\\raisebox{2pt}{\\footnotesize #8}}}%")
    add("}")
    add("")
    add("\\begin{document}")
    add("\\onecolumn")
    add("\\setlength{\\unitlength}{1in}")
    add("\\noindent\\begin{picture}(3.20,2.90)(0,0)")
    add("  \\linethickness{0.55pt}")

    panels = [
        ("Fold", FOLD_BASE, FOLD_MAX, FOLD_TICKS, FOLD_TITLE_Y),
        ("Flatten", FLAT_BASE, FLAT_MAX, FLAT_TICKS, FLAT_TITLE_Y),
    ]
    for title, base, ymax, ticks, title_y in panels:
        scale = AXIS_H / ymax
        add(f"  % {title} panel: 0-{ymax:g} scale, shared baseline.")
        add(f"  \\put({fmt(AXIS_X)},{fmt(base)}){{\\line(0,1){{{fmt(AXIS_H)}}}}}")
        add(f"  \\put({fmt(AXIS_X)},{fmt(base)}){{\\line(1,0){{2.62}}}}")
        for tick in ticks:
            y = base + tick * scale
            add(f"  \\put({fmt(AXIS_X)},{fmt(y)}){{\\line(-1,0){{0.055}}}}")
            add(f"  \\put({fmt(TICK_LABEL_X)},{fmt(y)}){{\\makebox(0,0)[r]{{\\footnotesize {tick}}}}}")
        add(f"  \\put({fmt(PANEL_CENTER_X)},{fmt(title_y)}){{\\makebox(0,0)[b]{{\\small {title}}}}}")
        for x in BAR_X:
            add(f"  \\put({fmt(x + BAR_W / 2)},{fmt(base)}){{\\line(0,-1){{0.045}}}}")
        add("")
        for model_index, (model, label) in enumerate(MODELS):
            task_rates = rates[(title, model)]
            for texture_index, texture in enumerate(("train", "test")):
                x = BAR_X[model_index * 2 + texture_index]
                seen = task_rates[("seen", texture)] / 2.0
                unseen = task_rates[("unseen", texture)] / 2.0
                overall = seen + unseen
                h_seen = seen * scale
                h_unseen = unseen * scale
                total = h_seen + h_unseen
                add(
                    f"  \\stackbar{{{fmt(x)}}}{{{fmt(base)}}}{{{fmt(base + h_seen)}}}"
                    f"{{{fmt(base + total)}}}{{{fmt(h_seen)}}}{{{fmt(h_unseen)}}}"
                    f"{{{fmt(total)}}}{{{overall:.1f}}}"
                )
        add("")
    add("  % Shared categorical labels: texture per bar, model per pair.")
    texture_words = ("Seen", "Unseen")
    for x, word in zip(BAR_X, texture_words * 3):
        center = x + BAR_W / 2
        add(f"  \\put({fmt(center)},{fmt(TEX_LINE1_Y)}){{\\makebox(0,0)[t]{{\\footnotesize {word}}}}}")
        add(f"  \\put({fmt(center)},{fmt(TEX_LINE2_Y)}){{\\makebox(0,0)[t]{{\\footnotesize tex.}}}}")
    for model_index, (_, label) in enumerate(MODELS):
        left = BAR_X[model_index * 2]
        right = BAR_X[model_index * 2 + 1] + BAR_W
        center = (left + right) / 2
        add(f"  \\put({fmt(center)},{fmt(MODEL_LABEL_Y)}){{\\makebox(0,0)[t]{{\\footnotesize {label}}}}}")
    add("")
    add("  % Legend inside the Fold panel upper right.")
    for text, y in LEGEND_ROWS:
        color = "\\seenColor" if text.startswith("Seen") else "\\unseenColor"
        add(f"  \\put({fmt(LEGEND_X)},{fmt(y)}){{\\colorpush{{{color}}}\\rule{{0.16in}}{{0.085in}}\\colorpop}}")
        add(f"  \\put({fmt(LEGEND_X)},{fmt(y)}){{\\framebox(0.16,0.085){{}}}}")
        add(f"  \\put({fmt(LEGEND_LABEL_X)},{fmt(y + 0.0425)}){{\\makebox(0,0)[l]{{\\footnotesize {text}}}}}")
    add(f"  \\put({fmt(YLABEL_X)},1.56){{\\makebox(0,0){{\\rotatebox{{90}}{{\\footnotesize SR (\\%)}}}}}}")
    add("\\end{picture}")
    add("\\end{document}")
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    FIGURE.write_text("\n".join(lines) + "\n")
    print(f"wrote {FIGURE}")


if __name__ == "__main__":
    main()
