#!/usr/bin/env python3
"""Generate the benchmark-style RGB-policy baselines figure.

Reuses the frozen run set from make_rgb_policy_baselines_compact and emits a
text-width grouped-bar grid at paper/figures/rgb-policy-baselines.tex. Rows
are tasks, columns are garment splits (Overall / Seen / Unseen), within-panel
groups are appearance pools, and colors encode models. Every bar carries its
success rate, so the figure reads like a benchmark table.
"""
from __future__ import annotations

from make_rgb_policy_baselines_compact import MODELS, ROOT, RUNS, fmt, success_rates

FIGURE = ROOT / "paper/figures/rgb-policy-baselines.tex"

MODEL_COLORS = {
    "pi05": "\\piColor",
    "groot": "\\grootColor",
    "diffusion": "\\diffColor",
}
TASKS = [
    ("Flatten", 0.52, 44.0, (0, 20, 40), "Flattening"),
    ("Fold", 2.44, 75.0, (0, 25, 50, 75), "Folding"),
]
SECTIONS = [
    ("Overall", lambda r, tex: (r[("seen", tex)] + r[("unseen", tex)]) / 2.0),
    ("Seen garments", lambda r, tex: r[("seen", tex)]),
    ("Unseen garments", lambda r, tex: r[("unseen", tex)]),
]
AXIS_X = 0.38
SLOT = 0.28
BAR_W = 0.19
BAR_OFF = 0.045
GROUP_GAP = 0.10
GROUP_W = 3 * SLOT
SECTION_STARTS = [0.50, 2.48, 4.46]
SECTION_W = 2 * GROUP_W + GROUP_GAP
AXIS_H = 1.05
TITLE_Y = {"Flatten": 1.80, "Fold": 3.72}
APP_LABEL_Y = {"Flatten": 0.38, "Fold": 2.30}
APP_WORDS = ("Train", "Held-out")
LEGEND_Y = 4.04
LEGEND_ENTRIES = [(3.70, "pi05"), (4.55, "groot"), (5.35, "diffusion")]
CANVAS_W, CANVAS_H = 6.75, 4.30
AXIS_END = SECTION_STARTS[-1] + SECTION_W


def bar_label(value: float) -> str:
    return f"{value + 1e-9:.1f}"


def main() -> None:
    rates = {key: success_rates(run) for key, run in RUNS.items()}
    lines: list[str] = []
    add = lines.append
    add("\\RequirePackage[T1]{fontenc}")
    add("\\documentclass[letterpaper,10pt,conference]{../ieeeconf}")
    add("\\usepackage{graphicx}")
    add("\\pagestyle{empty}")
    add("")
    add("% Generated by paper/scripts/make_rgb_policy_baselines.py; edit that script instead.")
    add("% Benchmark grid: rows = task, columns = garment split, groups = appearance, color = model.")
    add("\\newcommand{\\piColor}{0.161 0.616 0.561}")
    add("\\newcommand{\\grootColor}{0.847 0.463 0.349}")
    add("\\newcommand{\\diffColor}{0.914 0.769 0.416}")
    add("\\newcommand{\\colorpush}[1]{\\special{color push rgb #1}}")
    add("\\newcommand{\\colorpop}{\\special{color pop}}")
    add("% One model bar: x, baseline, height, label y, color macro, value label.")
    add("\\newcommand{\\modelbar}[6]{%")
    add("  \\put(#1,#2){\\colorpush{#5}\\rule{0.19in}{#3in}\\colorpop}%")
    add("  \\put(#1,#2){\\framebox(0.19,#3){}}%")
    add("  \\put(#1,#4){\\makebox(0.19,0)[b]{\\raisebox{2pt}{\\footnotesize #6}}}%")
    add("}")
    add("")
    add("\\begin{document}")
    add("\\onecolumn")
    add("\\setlength{\\unitlength}{1in}")
    add(f"\\noindent\\begin{{picture}}({fmt(CANVAS_W)},{fmt(CANVAS_H)})(-0.25,0)")
    add("  \\linethickness{0.55pt}")

    for task, base, ymax, ticks, task_word in TASKS:
        scale = AXIS_H / ymax
        add(f"  % {task} row: 0-{ymax:g} scale.")
        add(f"  \\put({fmt(AXIS_X)},{fmt(base)}){{\\line(0,1){{{fmt(AXIS_H)}}}}}")
        add(f"  \\put({fmt(AXIS_X)},{fmt(base)}){{\\line(1,0){{{fmt(AXIS_END - AXIS_X)}}}}}")
        for tick in ticks:
            y = base + tick * scale
            add(f"  \\put({fmt(AXIS_X)},{fmt(y)}){{\\line(-1,0){{0.055}}}}")
            add(f"  \\put(0.30,{fmt(y)}){{\\makebox(0,0)[r]{{\\footnotesize {tick}}}}}")
        add(f"  \\put(0.10,{fmt(base + AXIS_H / 2)}){{\\makebox(0,0){{\\rotatebox{{90}}{{\\small {task_word}}}}}}}")
        for section_index, (section_title, _) in enumerate(SECTIONS):
            start = SECTION_STARTS[section_index]
            add(f"  \\put({fmt(start + SECTION_W / 2)},{fmt(TITLE_Y[task])}){{\\makebox(0,0)[b]{{\\small {section_title}}}}}")
            for group_index, word in enumerate(APP_WORDS):
                group_center = start + group_index * (GROUP_W + GROUP_GAP) + GROUP_W / 2
                add(f"  \\put({fmt(group_center)},{fmt(APP_LABEL_Y[task])}){{\\makebox(0,0)[t]{{\\footnotesize {word}}}}}")
        for model_index, (model, _) in enumerate(MODELS):
            color = MODEL_COLORS[model]
            for section_index, (_, value_of) in enumerate(SECTIONS):
                start = SECTION_STARTS[section_index]
                task_rates = rates[(task, model)]
                for group_index, tex in enumerate(("train", "test")):
                    value = value_of(task_rates, tex)
                    x = start + group_index * (GROUP_W + GROUP_GAP) + model_index * SLOT + BAR_OFF
                    h = value * scale
                    add(f"  \\modelbar{{{fmt(x)}}}{{{fmt(base)}}}{{{fmt(h)}}}{{{fmt(base + h)}}}{{{color}}}{{{bar_label(value)}}}")
        add("")
    add("  % Model legend, top right.")
    for x, model in LEGEND_ENTRIES:
        label = dict(MODELS)[model]
        color = MODEL_COLORS[model]
        add(f"  \\put({fmt(x)},{fmt(LEGEND_Y)}){{\\colorpush{{{color}}}\\rule{{0.16in}}{{0.085in}}\\colorpop}}")
        add(f"  \\put({fmt(x)},{fmt(LEGEND_Y)}){{\\framebox(0.16,0.085){{}}}}")
        add(f"  \\put({fmt(x + 0.20)},{fmt(LEGEND_Y + 0.0425)}){{\\makebox(0,0)[l]{{\\footnotesize {label}}}}}")
    add("  \\put(-0.16,2.00){\\makebox(0,0){\\rotatebox{90}{\\footnotesize SR (\\%)}}}")
    add("\\end{picture}")
    add("\\end{document}")
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    FIGURE.write_text("\n".join(lines) + "\n")
    print(f"wrote {FIGURE}")


if __name__ == "__main__":
    main()
